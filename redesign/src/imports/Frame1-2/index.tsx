// ---------------------------------------------------------------------------
// Draggable header pieces (Portfolio, 2026 and the three nav labels).
// Each piece is moved with the CSS `translate` property, so its own rotation
// (`transform`) is untouched. Pieces can only be dragged inside the strip between
// the top of the page and the top of "Helena Mouro" (design px, 1440 wide).
// ---------------------------------------------------------------------------
const HEADER_DRAG_LIMIT_BOTTOM = 440; // visible top of the "Helena Mouro" letters
const HEADER_DRAG_PAD = 7; // the corner squares stick out ~6px past each box

function useHeaderDrag() {
  const offsets = useRef<Record<string, { x: number; y: number }>>({});
  const justDragged = useRef(false);

  const dragProps = (id: string) => ({
    onPointerDown: (e: React.PointerEvent<HTMLElement>) => {
      if (e.button !== 0) return;
      const el = e.currentTarget;
      const scale = window.innerWidth / 1440; // App.tsx scales the 1440px frame to the window
      const r = el.getBoundingClientRect();
      const box = {
        left: r.left / scale - HEADER_DRAG_PAD,
        right: r.right / scale + HEADER_DRAG_PAD,
        top: (r.top + window.scrollY) / scale - HEADER_DRAG_PAD,
        bottom: (r.bottom + window.scrollY) / scale + HEADER_DRAG_PAD,
      };
      const o0 = offsets.current[id] ?? { x: 0, y: 0 };
      const startX = e.clientX;
      const startY = e.clientY;
      let moved = false;
      el.setPointerCapture(e.pointerId);
      el.classList.add("is-dragging");

      const onMove = (ev: PointerEvent) => {
        const dx = (ev.clientX - startX) / scale;
        const dy = (ev.clientY - startY) / scale;
        if (!moved && Math.hypot(dx, dy) * scale < 4) return; // small movement = a click
        moved = true;
        const x = Math.min(Math.max(o0.x + dx, o0.x - box.left), o0.x + (1440 - box.right));
        const y = Math.min(Math.max(o0.y + dy, o0.y - box.top), o0.y + (HEADER_DRAG_LIMIT_BOTTOM - box.bottom));
        offsets.current[id] = { x, y };
        el.style.translate = `${x}px ${y}px`;
      };
      const onUp = () => {
        el.classList.remove("is-dragging");
        el.removeEventListener("pointermove", onMove);
        el.removeEventListener("pointerup", onUp);
        el.removeEventListener("pointercancel", onUp);
        if (moved) {
          justDragged.current = true; // swallow the click that follows a drag
          setTimeout(() => { justDragged.current = false; }, 0);
        }
      };
      el.addEventListener("pointermove", onMove);
      el.addEventListener("pointerup", onUp);
      el.addEventListener("pointercancel", onUp);
    },
    onDragStart: (e: React.DragEvent) => e.preventDefault(),
  });

  return { dragProps, justDragged };
}

